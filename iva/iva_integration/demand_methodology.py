def _validate(track, role=None):
    if track not in TRACKS:
        raise ValueError('unknown_research_track')
    if role is not None and role not in ROLES:
        raise ValueError('unknown_research_role')


def instructions(track, *, phase='discovery', role=None):
    """Return bounded methodology for a selected track; never broaden its scope."""
    _validate(track, role)
    if phase not in PHASES:
        raise ValueError('unknown_research_phase')
    parts = [_COMMON, _SOFTWARE if track == 'software' else _GOODS]
    if phase in ('plan', 'discovery'):
        if track == 'software':
            parts.append(_SOFTWARE_SOURCES)
        parts.append(_DISCOVERY)
    else:
        parts.append(_EVIDENCE)
    if role:
        parts.append(_ROLE[role])
    if phase in ('plan', 'synthesis'):
        parts.append('Следующая проверка должна закрывать конкретное неизвестное '
                     'текущего решения, иметь наблюдаемый критерий успеха/опровержения '
                     'и источник ожидаемых данных. Опрос, демонстрация и платный пилот '
                     'могут быть планом для владельца; не выполняй контакты/покупки '
                     'и не описывай запланированную проверку как состоявшуюся.')
    return '\n'.join(parts)


def query_suggestions(track, topic, *, role='buyer_problem'):
    """Return examples for a brief already scoped by the caller, not source URLs."""
    _validate(track, role)
    if not isinstance(topic, str) or '\x00' in topic:
        raise ValueError('invalid_research_topic')
    topic = ' '.join(topic.split()).strip()
    if not topic or len(topic) > 600:
        raise ValueError('invalid_research_topic')
    if track == 'software':
        suffixes = {
            'buyer_problem': ('site:qna.habr.com вручную автоматизация',
                              'site:habr.com inurl:comments не хватает',
                              'форум повторный ввод неудобно', 'заказ доработка интеграция бюджет'),
            'alternatives': ('site:habr.com миграция ограничения', 'отзывы программа недостаёт функции',
                             'документация тариф ограничения', 'бесплатная альтернатива настройка'),
            'foreign': ('user reviews manual workaround', 'software alternatives limitations pricing',
                        'site:github.com inurl:issues workaround', 'customer migration experience'),
            'critic': ('исправлено новая версия инструкция', 'бесплатно штатная функция настройка',
                       'site:qna.habr.com решено', 'site:habr.com inurl:comments альтернатива'),
        }[role]
    elif role == 'foreign':
        suffixes = ('customer experience alternatives', 'refund delivery warranty terms',
                    'referral commission payout conditions', 'independent reviews actual costs')
    elif role == 'critic':
        suffixes = ('отказ от покупки альтернатива', 'возврат гарантия спор',
                    'полная стоимость отзыв покупателя', 'условия комиссии отмена заказа')
    else:
        suffixes = ('отзыв покупателя опыт', 'форум проблема обходное решение',
                    'альтернатива полная стоимость', 'официальные условия доставка возврат')
    return [topic + ' ' + suffix for suffix in suffixes]


def source_family(url):
    """Location hints only: caller must verify authorship, content and independence."""
    try:
        parsed = urlsplit(url)
        if parsed.scheme not in ('http', 'https') or not parsed.hostname:
            return 'unknown'
        host, path = parsed.hostname.casefold(), parsed.path.casefold()
    except (ValueError, TypeError):
        return 'unknown'
    if host == 'qna.habr.com':
        return 'user_question_and_answers'
    if host in ('habr.com', 'www.habr.com'):
        if '/comments/' in path or path.endswith('/comments'):
            return 'habr_comment_thread'
        if '/companies/' in path:
            return 'company_publication'
        return 'habr_publication'
    if host in ('github.com', 'www.github.com') and any(part in path.split('/') for part in ('issues', 'discussions')):
        return 'public_issue_or_discussion'
    if host in ('trends.google.com', 'wordstat.yandex.ru'):
        return 'search_interest_signal'
    return 'unclassified_public_source'
